// Helper: Get country by ID
export const getCountryById = (id) => countries.find(c => c.id === id);

// Helper: Get countries by region
export const getCountriesByRegion = (region) => countries.filter(c => c.region === region);

// Helper: Get all regions
export const getRegions = () => [...new Set(countries.map(c => c.region))];

// Helper: Get all currencies (unique)
export const getCurrencies = () => {
  const seen = new Set();
  return countries.filter(c => {
    if (seen.has(c.currency.code)) return false;
    seen.add(c.currency.code);
    return true;
  }).map(c => c.currency);
};

