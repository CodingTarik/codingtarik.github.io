  <p className="text-sm text-amber-700 dark:text-amber-300"><strong>Mit der Faser</strong> (Pol zu Pol) schneiden = Streifen behalten Biss, perfekt zum Karamellisieren. <strong>Quer zur Faser</strong> schneiden = Zwiebel zerfällt schneller, gibt mehr Saft ab, wird weicher beim Kochen.</p>
